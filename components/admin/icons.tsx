export type ConsoleIconName = keyof typeof CONSOLE_ICONS;

export interface ConsoleIconProps {
  name: ConsoleIconName;
  /** Pixels. Defaults to 18, which sits well beside 16px text. */
  size?: number;
  className?: string;
}

/** A decorative icon: always hidden from assistive technology, so the visible or visually hidden text carries the meaning. */
export function ConsoleIcon({ name, size = 18, className }: ConsoleIconProps) {
  const Icon = CONSOLE_ICONS[name];
  return <Icon aria-hidden="true" focusable="false" size={size} strokeWidth={1.75} absoluteStrokeWidth className={className ? `shrink-0 ${className}` : "shrink-0"} />;
}
